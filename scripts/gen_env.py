#!/usr/bin/env python3
"""
OphthalmoAI: Secure Environment Configuration Generator.
Generates a local .env file with cryptographically secure random secrets.
"""

import os
import secrets

ENV_PATH = os.path.abspath(".env")
EXAMPLE_PATH = os.path.abspath(".env.example")

def generate_env(force: bool = False) -> str:
    if os.path.exists(ENV_PATH) and not force:
        print(f"[SKIP] Existing .env file found at {ENV_PATH}. Use --force to overwrite.")
        return ENV_PATH

    jwt_secret = secrets.token_hex(32)

    template = f"""# ==============================================================================
# OphthalmoAI Local Development Configuration (Generated by scripts/gen_env.py)
# ==============================================================================

# Database: SQLite for zero-setup local research; PostgreSQL for multi-user
DATABASE_URL=sqlite:///./ophthalmoai.db

# Runtime Environment
ENVIRONMENT=development
HOST=0.0.0.0
PORT=8000
FORCE_CPU=false
MODELS_DIR=./models
PERSIST_SCANS=false
MAX_FILE_SIZE_BYTES=20971520

# Cryptographic Security
JWT_SECRET_KEY={jwt_secret}
JWT_ALGORITHM=HS256
JWT_ACCESS_TOKEN_EXPIRE_MINUTES=480

# CORS & Networking
CORS_ORIGINS=http://localhost:5173,http://localhost:8080
CORS_ALLOW_CREDENTIALS=false

# Rate Limiting
PREDICT_RATE_LIMIT=10/minute
CHAT_RATE_LIMIT=30/minute
AUTH_RATE_LIMIT=20/minute

# AI Assistant Providers (Default: Mock/Local Ollama; Gemini requires opt-in key)
GEMINI_API_KEY=
GEMINI_MODEL=gemini-2.0-flash
OLLAMA_URL=
OLLAMA_MODEL=llama3.2:3b

# Clinical Gates
MC_DROPOUT_PASSES=8
ENABLE_UNCERTAINTY=true
ENABLE_IQA=true
MODEL_REGISTRY_JSON=./models/registry.json
"""

    with open(ENV_PATH, "w", encoding="utf-8") as f:
        f.write(template)

    print(f"[OK] Generated secure .env configuration at {ENV_PATH}")
    print(f"[OK] Cryptographic JWT_SECRET_KEY generated (64 hex characters)")
    return ENV_PATH

if __name__ == "__main__":
    import sys
    force_overwrite = "--force" in sys.argv
    generate_env(force=force_overwrite)
